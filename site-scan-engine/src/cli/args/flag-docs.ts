/** Markdown flag tables for docs/cli.md, generated from the flag table so the docs cannot drift from the parser. */

import { flagDefault } from './flag-default.js';
import { CommandName, FLAG_GROUP_ORDER, type FlagSpec } from './flag-spec.js';
import { FLAGS } from './flags.js';

export const FLAG_DOCS_BEGIN = '<!-- flags:begin (generated by `npm run docs:cli`; do not edit by hand) -->';
export const FLAG_DOCS_END = '<!-- flags:end -->';

function defaultOf(spec: FlagSpec): string {
    const value = flagDefault(spec);

    return value === null ? '' : `\`${value}\``;
}

/** A literal pipe would end the table cell. */
const cell = (text: string): string => text.replaceAll('|', '\\|');

function row(spec: FlagSpec): string {
    const name = cell(`${spec.short ? `\`-${spec.short}\`, ` : ''}\`--${spec.name}${spec.value ? ` ${spec.value}` : ''}\``);
    const notes = [
        spec.repeatable ? 'repeatable' : null,
        spec.requires ? `needs ${spec.requires.map((flag) => `\`--${flag}\``).join(', ')}` : null,
        spec.requiresOneOf ? `needs ${spec.requiresOneOf.map((flag) => `\`--${flag}\``).join(' or ')}` : null,
        spec.conflictsWith ? `not with ${spec.conflictsWith.map((flag) => `\`--${flag}\``).join(', ')}` : null,
    ].filter(Boolean).join('; ');
    const commands = spec.commands.map((command) => `\`${command}\``).join(' ');

    return `| ${name} | ${spec.type} | ${spec.config ? `\`${spec.config}\`` : 'command'} | ${defaultOf(spec)} | ${commands} | ${cell(spec.summary)}${notes ? ` (${notes})` : ''} |`;
}

/** One table per flag group, between the begin/end markers. */
export function renderFlagDocs(): string {
    const sections = FLAG_GROUP_ORDER.flatMap((group) => {
        const flags = FLAGS.filter((spec) => spec.group === group);
        if (flags.length === 0) {
            return [];
        }

        return [`#### ${group}`, '', '| Flag | Type | Config path | Default | Commands | Meaning |', '| --- | --- | --- | --- | --- | --- |', ...flags.map(row), ''];
    });

    return [FLAG_DOCS_BEGIN, '', ...sections, FLAG_DOCS_END].join('\n');
}

export const COMMAND_LIST: readonly string[] = Object.values(CommandName);
